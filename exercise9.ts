const opcao: number = 2;

switch (opcao) {
    case 1:
        console.log("Consultar pedido");
        break;
    case 2:
        console.log("Abrir chamado")
        break;
    case 3:
        console.log("Falar com atendente");
        break;
    case 4:
        console.log("Sair")
        break;
    default:
        console.log("Opção inválida");
}